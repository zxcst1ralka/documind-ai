
import { expect, test } from '@playwright/test'
import { randomUUID } from 'node:crypto'
import { fileURLToPath } from 'node:url'

test('регистрация, документы, чат с источником, отчёт и удаление', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('Имя', { exact: true }).fill('Проверка интерфейса')
  await page.getByLabel('Email', { exact: true }).fill('playwright-' + randomUUID() + '@example.com')
  await page.getByLabel('Пароль', { exact: true }).fill('E2E-Test-Password-2026')
  await page.getByRole('button', { name: 'Создать аккаунт' }).click()
  await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Загрузить документы' }).click()
  await page.getByLabel('Файлы документов').setInputFiles([
    { name: 'Договор версия 1.txt', mimeType: 'text/plain', buffer: Buffer.from('Срок оплаты договора составляет 10 рабочих дней после акта.') },
    { name: 'Договор версия 2.txt', mimeType: 'text/plain', buffer: Buffer.from('Срок оплаты договора составляет 15 рабочих дней после акта.') },
  ])
  await expect(page.getByRole('dialog').getByText('Загружен', { exact: true })).toHaveCount(2)
  await page.getByRole('button', { name: 'Готово', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Договор версия 1.txt' }).getByText('Готов')).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: 'Договор версия 2.txt' }).getByText('Готов')).toBeVisible()
  await page.getByRole('link', { name: /Договор версия 1.txt TXT/ }).click()
  await page.getByRole('link', { name: 'Задать вопрос' }).click()
  await page.getByRole('button', { name: 'Создать чат' }).click()
  await page.getByRole('textbox', { name: 'Вопрос по документам' }).fill('Какой срок оплаты договора в рабочих днях?')
  await page.getByRole('button', { name: 'Отправить вопрос' }).click()
  const citation = page.getByRole('button', { name: 'Источник 1, Абзац 1', exact: true })
  await expect(citation).toBeVisible()
  await citation.click()
  await expect(page.locator('blockquote')).toContainText('10 рабочих дней')
  const desktop = page.viewportSize()!
  await page.setViewportSize({ width: 390, height: 844 })
  await citation.click()
  await expect(page.getByRole('dialog', { name: 'Источник' }).locator('blockquote')).toContainText('10 рабочих дней')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.setViewportSize(desktop)

  const navigation = page.getByRole('navigation', { name: 'Рабочее пространство' })
  await navigation.getByRole('link', { name: 'Анализ', exact: true }).click()
  await page.getByRole('combobox', { name: 'Документ', exact: true }).selectOption({ label: 'Договор версия 1.txt' })
  await page.getByRole('combobox', { name: 'Режим', exact: true }).selectOption('short')
  await page.getByRole('button', { name: 'Начать анализ' }).click()
  await expect(page.getByRole('heading', { name: 'Краткое резюме' })).toBeVisible()
  await navigation.getByRole('link', { name: 'Сравнение', exact: true }).click()
  await page.getByRole('combobox', { name: 'Исходная версия', exact: true }).selectOption({ label: 'Договор версия 1.txt' })
  await page.getByRole('combobox', { name: 'Новая версия', exact: true }).selectOption({ label: 'Договор версия 2.txt' })
  await page.getByRole('button', { name: 'Сравнить версии' }).click()
  await expect(page.getByText('Изменено 1')).toBeVisible()
  await page.getByRole('button', { name: 'Экспорт', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать отчёт' }).click()
  expect((await download).suggestedFilename()).toMatch(/\.pdf$/)
  await expect(page.getByRole('dialog')).toBeHidden()
  await navigation.getByRole('link', { name: 'Документы', exact: true }).click()
  await page.getByRole('link', { name: /Договор версия 1.txt TXT/ }).click()
  await page.getByRole('button', { name: 'Удалить документ' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Удалить', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Договор версия 1.txt' })).toHaveCount(0)
})

test('главная на мобильном, тема и навигация с клавиатуры', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Ваши документы')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.getByRole('button', { name: 'Светлая тема' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Стоимость', exact: true }).click()
  await page.getByRole('button', { name: /Показать источник/ }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('[data-highlighted="true"]')).toContainText('120 000 рублей')
  await page.getByText('Какие файлы можно загрузить?').focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText('PDF, включая сканы, DOCX', { exact: false })).toBeVisible()
})

test('загрузка скана, распознанный текст и ссылка на страницу PDF', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('Имя', { exact: true }).fill('Проверка OCR')
  await page.getByLabel('Email', { exact: true }).fill('ocr-' + randomUUID() + '@example.com')
  await page.getByLabel('Пароль', { exact: true }).fill(randomUUID())
  await page.getByRole('button', { name: 'Создать аккаунт' }).click()
  await page.getByRole('link', { name: 'Загрузить документы' }).click()
  const fixture = fileURLToPath(new URL('../../../backend/tests/fixtures/scanned-contract.pdf', import.meta.url))
  await page.getByLabel('Файлы документов').setInputFiles(fixture)
  await expect(page.getByRole('dialog').getByText('Загружен', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Готово', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'scanned-contract.pdf' }).getByText('Готов', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: /scanned-contract.pdf PDF/ }).click()
  await expect(page.getByText('Распознано через OCR')).toBeVisible()
  await page.getByRole('button', { name: 'Текст', exact: true }).click()
  await expect(page.locator('.extracted-text')).toContainText('10 рабочих дней')
  await page.getByRole('link', { name: 'Задать вопрос' }).click()
  await page.getByRole('button', { name: 'Создать чат' }).click()
  await page.getByRole('textbox', { name: 'Вопрос по документам' }).fill('Срок оплаты — сколько рабочих дней?')
  await page.getByRole('button', { name: 'Отправить вопрос' }).click()
  await page.getByRole('button', { name: 'Источник 1, Страница 1 · OCR', exact: true }).click()
  const source = page.locator('.chat-source')
  await expect(source.locator('blockquote')).toContainText('10 рабочих дней')
  await source.getByRole('link', { name: 'Открыть документ' }).click()
  await expect(page).toHaveURL(/\/app\/documents\/[^?]+\?page=1$/)
  await expect(page.locator('.react-pdf__Page canvas')).toBeVisible()
})
